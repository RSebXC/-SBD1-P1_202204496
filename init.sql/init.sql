CREATE TABLE Usuarios (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  identificacion_nacional VARCHAR(20) UNIQUE NOT NULL,
  nombre VARCHAR(50) NOT NULL,
  apellido VARCHAR(50) NOT NULL,
  correo VARCHAR(100) UNIQUE NOT NULL,
  telefono VARCHAR(20),
  activo NUMBER(1) DEFAULT 1,
  fecha_registro TIMESTAMP DEFAULT SYSTIMESTAMP,
  correo_confirmado NUMBER(1) DEFAULT 0,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  update_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE Direcciones (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id NUMBER,
  direccion VARCHAR(200) NOT NULL,
  ciudad VARCHAR(50) NOT NULL,
  pais VARCHAR(50) NOT NULL,
  codigo_postal VARCHAR(10),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  update_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  FOREIGN KEY (usuario_id) REFERENCES Usuarios(id) ON DELETE CASCADE
);

CREATE TABLE Metodos_Pago (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id NUMBER,
  tipo VARCHAR(50) NOT NULL,
  detalles VARCHAR(500) NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  update_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  FOREIGN KEY (usuario_id) REFERENCES Usuarios(id) ON DELETE CASCADE
);

CREATE TABLE Pagos (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha_transaccion TIMESTAMP DEFAULT SYSTIMESTAMP,
  monto NUMBER(10,2) NOT NULL,
  metodo_pago_id NUMBER,
  estado VARCHAR(20) CHECK (estado IN ('pendiente', 'aprobado', 'rechazado')) NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  update_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  FOREIGN KEY (metodo_pago_id) REFERENCES Metodos_Pago(id) ON DELETE SET NULL
);

CREATE TABLE Trabajadores (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  identificacion_nacional VARCHAR(20) UNIQUE NOT NULL,
  nombre VARCHAR(50) NOT NULL,
  apellido VARCHAR(50) NOT NULL,
  cargo VARCHAR(50) NOT NULL,
  departamento VARCHAR(50) NOT NULL,
  telefono VARCHAR(20),
  correo_institucional VARCHAR(100) UNIQUE NOT NULL,
  activo NUMBER(1) DEFAULT 1,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  update_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE Sedes (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  ubicacion VARCHAR(200) NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  update_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE Trabajadores_Logistica (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sede_id NUMBER,
  FOREIGN KEY (sede_id) REFERENCES Sedes(id) ON DELETE CASCADE
);

CREATE TABLE Categorias (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  update_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE Productos (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku VARCHAR(50) UNIQUE NOT NULL,
  nombre VARCHAR(100) NOT NULL,
  descripcion VARCHAR(500),
  precio NUMBER(10,2) NOT NULL,
  slug VARCHAR(100) UNIQUE NOT NULL,
  categoria_id NUMBER,
  activo NUMBER(1) DEFAULT 1,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  update_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  FOREIGN KEY (categoria_id) REFERENCES Categorias(id) ON DELETE SET NULL
);

CREATE TABLE Inventario (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id NUMBER,
  sede_id NUMBER,
  cantidad INT NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  update_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  FOREIGN KEY (producto_id) REFERENCES Productos(id) ON DELETE CASCADE,
  FOREIGN KEY (sede_id) REFERENCES Sedes(id) ON DELETE CASCADE
);

CREATE TABLE Orden_Compra (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id NUMBER,
  fecha_creacion TIMESTAMP DEFAULT SYSTIMESTAMP,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  update_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  FOREIGN KEY (usuario_id) REFERENCES Usuarios(id) ON DELETE CASCADE
);

CREATE TABLE Orden_Productos (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id NUMBER,
  producto_id NUMBER,
  cantidad INT NOT NULL,
  precio_unitario NUMBER(10,2) NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  update_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  FOREIGN KEY (orden_id) REFERENCES Orden_Compra(id) ON DELETE CASCADE,
  FOREIGN KEY (producto_id) REFERENCES Productos(id) ON DELETE CASCADE
);

CREATE TABLE Envios (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id NUMBER,
  fecha_despacho DATE NOT NULL,
  direccion_entrega VARCHAR(255) NOT NULL,
  empresa_transporte VARCHAR(100) NOT NULL,
  numero_seguimiento VARCHAR(50) UNIQUE NOT NULL,
  estado VARCHAR(20) CHECK (estado IN ('en tránsito', 'entregado', 'devuelto')) NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  update_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  FOREIGN KEY (orden_id) REFERENCES Orden_Compra(id) ON DELETE CASCADE
);

CREATE TABLE Devoluciones (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id NUMBER,
  producto_id NUMBER,
  fecha_solicitud TIMESTAMP DEFAULT SYSTIMESTAMP,
  motivo VARCHAR(255) NOT NULL,
  estado VARCHAR(20) CHECK (estado IN ('en revisión', 'aprobada', 'rechazada')) NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  update_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  FOREIGN KEY (orden_id) REFERENCES Orden_Compra(id) ON DELETE CASCADE,
  FOREIGN KEY (producto_id) REFERENCES Productos(id) ON DELETE CASCADE
);

CREATE TABLE Traslados_Productos (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  almacen_origen_id NUMBER,
  almacen_destino_id NUMBER,
  fecha_movimiento TIMESTAMP DEFAULT SYSTIMESTAMP,
  fecha_estimada_llegada DATE,
  estado_traslado VARCHAR(20) NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  update_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  FOREIGN KEY (almacen_origen_id) REFERENCES Sedes(id) ON DELETE CASCADE,
  FOREIGN KEY (almacen_destino_id) REFERENCES Sedes(id) ON DELETE CASCADE
);

CREATE TABLE Traslado_Producto (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  traslado_id NUMBER,
  producto_id NUMBER,
  cantidad INT NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  update_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  FOREIGN KEY (traslado_id) REFERENCES Traslados_Productos(id) ON DELETE CASCADE,
  FOREIGN KEY (producto_id) REFERENCES Productos(id) ON DELETE CASCADE
);